// Funde torso + brazos + piernas en 18 filas de 17 caracteres (leyenda intacta).
export function figura({ mira = 'frente', brazos = 'neutro', piernas = 'neutro' } = {}) {
  const t = TORSO[mira] ?? TORSO.frente, b = BRAZOS[brazos] ?? BRAZOS.neutro, p = PIERNAS[piernas] ?? PIERNAS.neutro;
  const filas = t.map((fila, i) => [...fila].map((c, j) => (b[i][j] !== '.' ? b[i][j] : c)).join(''));
  return filas.concat(p);
}

// Las celdas ocupadas de una figura, con su papel: 'n' cuerpo, 'o' ojo, 'b' boca.
export function celdasDe(filas) {
  const out = [];
  filas.forEach((fila, y) => [...fila].forEach((c, x) => {
    if (c === '.' || c === ' ') return;
    out.push({ x, y, c: c === 'E' ? '0' : c === 'S' ? '_' : c, p: c === 'E' ? 'o' : c === 'S' ? 'b' : 'n' });
  }));
  return out;
}
